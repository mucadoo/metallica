<header class="head">
		<h1>Kirk Hammet</h1>
		</header>
	<img class="imagens" src="<?= BASE_URL ?>/media/kirk.jpg">
	<p class="paragrafo"><b>Nome completo:</b> Kirk Lee Stuart Hammett<br>
	<b>Instrumento:</b> Guitarra<br>
<b>Nascido em:</b> 18 de Novembro de 1962<br>
<b>Cidade Natal:</b> São Francisco, Califórnia<br>
<b>Características:</b> 1,70 m, 60,78 Kg, cabelos e olhos castanhos.<br>
<b>Antes do Metallica:</b> Tocou no Exodus.<br>
<b>Escuta:</b> Jimi Hendrix, UFO, Black Sabbath, Deep Purple, Led Zeppelin, Kiss, John Coltrane, Goul, Mule, Chet Baker, Prez Prado, AIC, David Bowie, U2, King Crimson, Robert Johnson.<br>
<b>Heróis:</b> Boris Karloff, Bela Lugosi, Jimi Hendrix, Chet Baker, Diane Arbus, John Coltrane, Charles Bukowski, Edward Munch, Joel Peter Whitkin.<br>
<b>Primeiro Show:</b> Day on the Green juntamente com Eagles, Steve Miller, Heart e Foreigner.<br>
<b>Se considera:</b> Cheiroso, feio, feliz, obcessivo, progressivo, curioso.<br><br>

Kirk Hammett tem a distinção de ser o mais coerente e contente membro do Metallica. Usualmente em um bom humor e infalivelmente genial, sua natureza ensolarada pode acreditar no 
fato de que ele é um sério, muito talentoso guitarrista.<br><br>
Perto do fim dos anos 60, o irmão "hippie" mais velho de Kirk, virou ele para Jimi Hendrix, Santana, Led Zeppelin e para outros sons daquela época. Quando o irmão Rick estava
 longe na escola, o jovem Kirk pegava a guitarra dele e tentava tocar. Ele começou tocar seriamente quando ele tinha 15 anos e formou a sua primeira banda de garagem "mais ou menos 2 semanas mais tarde".<br><br>
Kirk, um amigo que tinha recentemente adquirido um baixo e um outro amigo que cantava, plugavam tudo à um único amplificador na garagem do baixista. Seus primeiros sets consistia 
de 2 músicas: "Wild Thing" e "Purple Haze" de Hendrix, incluindo "15 minutos de horríveis solos de guitarra". Convenientemente, o amplificador (emprestado pela escola de Kirk) explodiu.<br><br>
Depois da escola, Kirk ia para o emprego em uma mercearia e uma lanchonete para conseguir comprar guitarras e um amplificador. Aos 20 anos, ele decidiu ter aulas de guitarra e 
estudou com Joe Satriani por aproximadamente um ano, para aperfeiçoar sua técnica. Em 1981, Kirk e o baterista Tom Hunting formaram a banda Exodus. Eles se apresentaram em clubes locais ao redor e uma vez 
tocaram em um mesmo bico com o Metallica, certamente antes que a banda voasse para Nova York para gravar o seu primeiro álbum. Isto foi enquanto o Metallica estava decidindo que 
o guitarrista Dave Mustaine tinha que ir embora da banda. Quando Kirk recebeu um convite deles para juntar-se a banda, ele achou que isto era uma brincadeira de Primeiro de Abril. Não era brincadeira, Kirk 
voou para Nova York onde ele apertou James, Cliff, e Lars. Kirk lembra que aquela foi uma situação estranha, porque ele realmente não conhecia eles. Ele só percebeu que estava contratado, 
quando ele foi incluído na gravação do álbum "Kill 'Em All". Casualmente, o começo para o quê seria um relacionamento momentâneo. A criatividade e o sangue frio de Kirk são um quarto do quê faz o Metallica grande. </p>
