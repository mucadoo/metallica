		<h1>James Hetfield</h1>
		</header>
		<img class="imagens" src="<?= BASE_URL ?>/media/james.jpg">
		<p class="paragrafo"><b>Nome completo:</b> James Alan Hetfield<br>
<b>Instrumento:</b> Vocal, Guitarra<br>
<b>Nascido em:</b> 03 de Agosto de 1963<br>
<b>Cidade Natal:</b> Los Angeles, Califórnia<br>
<b>Características:</b> 1,85 m, 81,65 Kg, cabelos castanhos, olhos azuis.<br>
<b>Antes do Metallica:</b> Tocou no Obsession, Leather Charm.<br>
<b>Carreira pré-Metallica:</b> Trabalhou em uma fábrica de adesivos.<br>
<b>Escuta:</b> Black Sabbath, Motorhead, Skynyrd, Thin Lizzy, Tom Waits, Nick Cave, Spegetti,Western Soundtracks<br>
<b>Filmes:</b> The Good, The Bad and The Ugly, Easy Rider, Sling Blade, Pulp Fiction, Vanishing Point<br>
<b>Heróis:</b> Clint Eastwood, Pops Hetfield.<br>
<b>Primeiro Show:</b> Aerosmith & AC/DC, 1978, Long Beach, California.<br>
<b>Se considera:</b> Rude, honesto, teimoso.<br><br>
James Hetfield é uma raridade no mundo do rock 'n' roll. Um homen de frente que preferivelmente fica atrás quando se discute 
sobre a sua banda. O mais secreto membro do Metallica, James não faz nenhum segredo do fato de que ele não gosta de fazer entrevistas 
e prefere deixar a sua música falar por ele. Em raras ocasiões quando ele fala, ele é honesto, objetivo e extremamente humilde, todas 
as características que se apliaca ao Metallica como uma banda. Pessoalmente, ele pode ser tímido ou desinibído, quieto ou barulhento, 
dependendo do seu humor. Pergunte à seis diferentes pessoas que conheceram-no, sobre o que ele gosta, e você conseguirá seis diferentes respostas. <br><br>
O filho do rigoroso Christian Scientists, James era uma criança quieta, dentro dos esportes "não era um Denis o Pimentinha". 
Seu irmão mais velho tocava bateria em uma banda local e girou James para dentro do rock em geral, e Black Sabbath em particular. 
No ano da terceira série, a família Hetfield mudou-se de Downey para LaBrea, Califórnia, onde James frequentava realmente um colégio. " 
Isto era o tipo de lugar onde era tabu gostar de esportes e ter cabelos longos". James manteve o cabelo e a inocência dentro de sua guitarra.
 Ele tocava por enquanto "na banda da escola" Obsession, fazendo a maioria das vezes covers de Zeppelin e Sabbath, e mais tarde formou Leather Charm. <br><br>
Era mais ou menos nesta época que James conheceu Ron McGovney, o qual deveria ser em breve o primeiro baixista do Metallica. Não era até 
que James conheceu Lars Ulrich, porém, através de um anúncio no jornal Recycler, que o Metallica foi formado. Originalmente o cantor da banda, 
James se saiu muito bem fazendo a guitarra base enquanto eles não encontravam alguém mais com o tato certo. Mais tarde, Metallica procurava um homem 
de frente, tanto que James (o qual humildemente descreve ele mesmo como um "cantor ou clamador ou berrador") conseguiu concentrar na guitarra e cantar 
ao mesmo tempo. Ele acreditava que poderia desconcentrar-se fazendo as duas coisas ao mesmo tempo. Mas isto nunca aconteceu e ele continua fazendo ambos.
 Metallica somente não seria Metallica de algum outro jeito.<br><br>
