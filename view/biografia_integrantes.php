		<h1>Lars Ulrich</h1>
		</header>
	<img class="imagens" src="<?= BASE_URL ?>/media/lars.jpg">
	<p class="paragrafo"><b>Nome Completo:</b> Lars Ulrich<br>
<b>Instrumento:</b> Bateria<br>
<b>Nascido em:</b> 26 de Dezembro de 1963<br>
<b>Cidade Natal:</b> Gentofte, Dinamarca.<br>
<b>Características:</b> 1,70 m, 58,97 Kg, cabelo castanho claro, olhos verdes.<br>
<b>Antes do Metallica:</b> Nada.<br>
<b>Carreira pré-Metallica:</b> Entregador de jornal, frentista.<br>
<b>Escuta:</b> Oasis, AIC, Black Grape, sua esposa.<br>
<b>Heróis:</b> Guilhermo Vilas (jogador de tênis argentino), Ritchie Blackmore, Ace Frehley.<br>
<b>Primeiro Show:</b> Deep Purple, 1973, Copenhagen.<br>
<b>Se considera:</b> Apressado, teimoso, espontâneo, sarcástico, comunicativo, ciumento, dedo-duro.<br><br>
Um dos co-fundadores do Metallica, Lars é muitas vezes chamado para ser o porta-voz da banda. Falador, várias vezes 
intensamente sério, especialmente quando se discute sobre sua banda.<br><br>
Nascido e crescido em Copenhague, o jovem Lars seguiu os passos de seu pai que era tenista, ele competiu seriamente no
 esporte até que sua família mudou-se para Los Angeles em 1980. Logo após ter descoberto que ele estava apenas engatinhando
 perto dos bons jogadores de tênis, Lars abandonou o tênis como uma carreira e foi atrás de sua grande vocação e grande paixão:
 a música, especialmente baterias. Hábil nas bateras e batendo em caixas de papelão com varas desde os 12 anos de idade, Lars
 conversou com sua avó para comprar um kit de bateria em 1977 e praticar em sua casa imaginando que ele era o Ian Paice do Deep Purple.<br><br>
Uma vez em Los Angeles, Lars estava desanimado porque estava muito difícil em encontrar alguém que tivesse sido influenciado por 
Iron Maiden, Saxon, Motorhead e outras bandas de metal europeu. Ele procurou por um bom guitarrista que estava a fim de formar uma banda 
de heavy metal, e ele encontrou James Hetfield, um cara que apreciava as melhores coisas no heavy metal. Alguns meses mais tarde, eles 
fizeram o nascimento do Metallica na garagem de Lars. Nós duvidamos que o garoto que sonhava em jogar em Wimbledon arrependeu-se e mudou 
a sua carreira para a carreira que ele tem agora, tocando em estádios de um tipo diferente que ele imaginava em ser antes, quando ele era jogador de tênis.
</p>
