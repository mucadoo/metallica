		<h1>Robert Trujillo</h1>
		</header>
	<img class="imagens" src="<?= BASE_URL ?>/media/trujillo.jpg">
	<p class="paragrafo"><b>Nome completo:</b> Roberto Agustín Miguel Santiago Samuel Trujillo Veracruz Batista<br>
<b>Instrumento:</b> Baixo<br>
<b>Nascido em:</b> 23 de Outubro de 1964<br>
<b>Cidade Natal:</b> Santa Monica, Califórnia<br>
<b>Características:</b> 1,75 m, 82 Kg, olhos castanhos e cabelos castanho escuro.<br>
<b>Antes do Metallica:</b> Tocou no Suicidal Tendencies, Infectious Grooves, Jerry Cantrell, Ozzy Osbourne.<br>
<b>Escuta:</b> Black Sabbath, Larry Graham, Bootsy Collins, Marcus Miller, John McLaughlin, Jimmy Johnson, música clássica, rock, funk e jazz.<br>
<b>Influências:</b> Jaco Pastorious, Geezer Butler, Larry Graham.<br>
<b>Se considera:</b> Teimoso, fácil, quieto, barulhento, fixo, perturbado.<br><br>
O baixista Robert Trujillo (Roberto﻿ Agustin Miguel Santiago Samuel Trujillo Veracruz; Santa Mônica, Califórnia, 23 de outubro de 1964) tocou 
com o Suicidal Tendencies, Black Label Society, Infectious Grooves, Jerry Cantrell, Ozzy Osbourne e entrou para o Metallica em 2003.<br><br>

A carreira de Trujillo começou quando ele conheceu Mike Muir e Rocky George da banda Suicidal Tendencies. Ele mostrou bom domínio do contrabaixo e
 tocou com o grupo por um período considerável. Seu estilo e talento foram apreciados pela banda que o levou como baixista. Na década de noventa Muir e 
 Trujillo começaram o funk rock, com a banda ''Infectious Grooves''. Robert foi baixista do grupo durante vários anos até que ele deixou a banda, e se 
 juntou com Ozzy Osbourne. Lá ele permaneceu até 2003, quando foi convidado para participar da grande e famosa banda de thrash metal estadunidense, Metallica.
 A banda não era desconhecida para Trujillo. Ele a conheceu antes, quando sua banda estava abrindo um show do metallica, em 1994 no Summer Shad Tour.<br><br>
Para gravar o álbum St. Anger, do Metallica, foi oferecido a Robert US$ 1.000.000 Este preço foi, segundo Lars Ulrich, porque eles queria mostrar o quão sérios eram. 
Entre a saída de Jason Newsted e a chegada de Robert Trujillo foi Bob Rock (ex-produtor 1991-2006) o baixista temporário da banda.<br><br>
