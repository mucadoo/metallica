Depois do grande sucesso alcançado com “Master of Puppets”, quando a banda estava em seu melhor momento, acontece a pior tragédia da trajetória do grupo. 
Ainda em 1986, durante a turnê do disco anterior, um acidente com o ônibus da banda na Suécia, mata o baixista Cliff Burton. Depois de muito se pensar sobre
 a continuidade da banda, resolvem seguir em frente. E para o lugar deixado pelo lendário baixista, convocam Jason Newsted da banda FLOTSAN AND JETSAM. Como 
 teste para o novo membro gravam o EP “Garage Days Re-Revisited” em 1987, só com covers.<br><br>
Somente um ano mais tarde soltam o quarto álbum de estúdio, “...And Justice For All”, que na época foi lançado como disco duplo, devido a sua longa duração.
 Apesar de ter contado com os mesmos produtores do álbum anterior, este disco tem um som mais abafado. O baixo do novo integrante é praticamente inaudível, bem
 diferente dos anteriores, onde este instrumento era de fundamental importância no som do grupo. Se isso foi proposital para funcionar como luto ao ex-integrante, nunca saberemos.<br><br>
Deixando os problemas com a produção de lado. Este é sem dúvidas um grande trabalho. “Blackened”, que abre o disco, é um petardo violento, no melhor estilo METALLICA. A faixa-título é um 
épico de quase 10 minutos, com ótimos riffs de guitarra e quebras rítmicas, uma das melhores músicas do grupo em minha opinião. “The Eye of the Beholder” e “Harvester of Sorrow” também merecem 
destaque. A primeira uma música pesada e com um belo refrão e a segunda, com poderosos riffs.<br><br>
“One” é uma música singular na carreira da banda. Foi a responsável por colocar a banda no mainstream, com seu clipe veiculado aos montes na MTV americana. O fato é que essa é uma das melhores 
composições do grupo, seu começo suave e belo desemboca numa pancadaria sem precedentes nos minutos finais com direito a passagens fenomenais dos bumbos de Lars.<br><br>
As demais músicas, ainda que muito boas, acabam passando meio despercebido para muitas pessoas. Pois, mesmo tendo qualidade inegável, a banda já havia feito coisas ainda melhores anteriormente, 
o que acabou ofuscando-as um pouco, ainda mais colocadas lado-a-lado com as músicas já citadas presentes neste álbum.
