            After the great success achieved with “Master of Puppets,” when the band was at its peak, the worst tragedy in the group’s history occurred.
            Still in 1986, during the tour for the previous album, a bus accident in Sweden killed bassist Cliff Burton. After much thought about the band’s
            continuity, they decided to move forward. And to fill the void left by the legendary bassist, they recruited Jason Newsted from the band FLOTSAM AND JETSAM.
            As a test for the new member, they recorded the EP “Garage Days Re-Revisited” in 1987, consisting only of covers.<br><br>
            Only a year later, they released their fourth studio album, “...And Justice For All,” which at the time was released as a double album due to its
            long duration. Despite having the same producers as the previous album, this record has a more muffled sound. The new member’s bass is practically
            inaudible, quite different from previous albums where this instrument was of fundamental importance to the band’s sound. Whether this was intentional
            as a form of mourning for the former member, we will never know.<br><br>
            Putting production issues aside, this is undoubtedly a great work. “Blackened,” which opens the album, is a violent blast in the best METALLICA style.
            The title track is an epic of almost 10 minutes, with great guitar riffs and rhythmic breaks, one of the best songs by the group in my opinion.
            “The Eye of the Beholder” and “Harvester of Sorrow” also deserve attention. The first is a heavy song with a beautiful chorus, and the second, with
            powerful riffs.<br><br>
            “One” is a unique song in the band’s career. It was responsible for putting the band in the mainstream, with its music video heavily aired on American
            MTV. The fact is that this is one of the group’s best compositions, its smooth and beautiful beginning leading to unprecedented pandemonium in the
            final minutes, with phenomenal drumming passages from Lars.<br><br>
            The other songs, although very good, end up going somewhat unnoticed by many people. Even though they have undeniable quality, the band had done even
            better things before, which somewhat overshadowed them, especially when placed alongside the aforementioned songs on this album.
