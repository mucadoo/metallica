Nada mais do que cinco anos após o lançamento do polêmico “St Anger”, o METALLICA lança o muito aguardado (com ar de desconfiança) 
“Death Magnetic” e mais uma vez sob promessas e esperança de um retorno aos tempos áureos da banda. E o resultado aqui encontrado é
 deveras satisfatório e acredito que tenha suprido, pela primeira vez em muitos anos, as expectativas dos fãs.<br><br>
“Death Magnetic” não soa exatamente como os discos dos anos 80 da banda, mas tem muito do que se ouvia neles. As músicas são fortes,
 muitas vezes agressivas e rápidas como aquelas de antigamente, mas principalmente consistentes. Os velhos riffs estão de volta, com 
 peso e melodia, tal como devem ser. Os solos também voltam a dar as caras por aqui e só mostram que nunca deveriam ter deixado de
 estarem presentes nas músicas do grupo. As composições são de muito bom gosto e mostram aos ouvintes uma mistura da qualidade e força 
 de “Master of Puppets” e a inovação de “Load”. Uma autentica volta ao thash metal, porém sem soar datado ou nostálgico. Um álbum mais METALLICA seria impossível.<br><br>
A banda mostrou que pode e sabe sim fazer um som pesado e de qualidade, como nos velhos tempos. Talvez o que estivesse os atrapalhando era 
o produtor Bob Rock, aqui substituído pelo competente Rick Rubin, que, diga-se de passagem, fez um excelente trabalho, deixando os 
instrumentos limpos sem que perdessem o peso.<br><br>
Como destaques podemos citar a veloz “All Nightmare Long”, “Cyanide”, a semi-balada “The Day That Never Comes”, a pesadíssima 
“My Apocalipse”, e a melhor de todas “That Was Just Your Life”. Vale também uma menção honrosa à volta das faixas instrumentais,
 com a forte “Suicide and Redemption”. Com tudo “Death Magnetic” deixa claro que o METALLICA ainda tem muita lenha pra queimar e
 merece estar no topo do cenário Rock/Metal.
