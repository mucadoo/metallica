            No less than five years after the release of the controversial “St. Anger,” METALLICA released the much-anticipated (with an air of skepticism) “Death Magnetic,” once again filled with promises and hopes of a return to the band’s golden era. The result found here is quite satisfactory and I believe, for the first time in many years, it has met the fans’ expectations.<br><br>
            “Death Magnetic” doesn’t sound exactly like the band’s albums from the 80s, but it retains much of their essence. The songs are strong, often aggressive and fast like those from the past, but most importantly, they are consistent. The old riffs are back, with weight and melody, just as they should be. The solos also make a return and only show that they should never have been absent from the group’s songs. The compositions are in very good taste and show listeners a mix of the quality and power of “Master of Puppets” and the innovation of “Load.” An authentic return to thrash metal, but without sounding dated or nostalgic. A more METALLICA album would be impossible.<br><br>
            The band has shown that they can and do know how to make heavy and quality sound, like in the old days. Perhaps what was hindering them was producer Bob Rock, who has been replaced here by the competent Rick Rubin, who, by the way, did an excellent job, keeping the instruments clean without losing their weight.<br><br>
            Highlights include the fast “All Nightmare Long,” “Cyanide,” the semi-ballad “The Day That Never Comes,” the very heavy “My Apocalypse,” and the best of all “That Was Just Your Life.” An honorable mention also goes to the return of instrumental tracks, with the strong “Suicide and Redemption.” With all that, “Death Magnetic” makes it clear that METALLICA still has a lot of fuel left to burn and deserves to be at the top of the Rock/Metal scene.
