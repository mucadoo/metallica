Seis anos após o último disco de músicas inéditas da banda, é anunciado o lançamento de “St. Anger”.
 E junto com ele mais uma vez as promessas de que a banda retornaria ao estilo pesado e agressivo do início de sua carreira.<br><br>
Ainda na fase de composição e gravação das músicas, o grupo tem sua segunda baixa na carreira e mais uma vez com o baixista. Dessa vez, 
Jason Newsted deixa a banda (ou é chutado dela) alegando divergências musicais. Para seu lugar foi recrutado o excelente Robert Trujillo 
(SUICIDAL TENDENCIES, OZZY OUSBORNE). Entretanto, ele não participou das gravações do novo álbum. O baixo ficou a cargo do produtor Bob Rock.<br><br>
E tal como anunciado anteriormente o novo disco é pesado e agressivo. Aqui não temos baladas, no máximo algumas passagens leves em algumas músicas. 
Porém, o maior problema aqui é a produção, que deixou tudo com um som estranho. As guitarras estão baixas e a bateria, além de muito alta, parece um 
latão de lixo. Outro grande erro está na ausência de solos de guitarra. Aliás, muito estranha a decisão da banda de tirá-los das músicas, sendo que
Kirk Hammet sempre foi muito bom nisso. Dessa forma, muitas das músicas (todas têm entre cinco e oito minutos de duração) fiquem muito repetitivas. 
Já que não têm solos, pelo menos, poderiam ser mais curtas.<br><br>
Contudo, “St. Anger” está muito longe de fazer frente aos clássicos discos do grupo. As composições não têm o mesmo requinte de antigamente. 
Aquelas músicas não eram apenas pesadas. Eram compostas por riffs e solos inspirados. Bateria veloz e técnica. Sem falar no baixo. Aliás, onde está o baixo em “St. Anger”?<br><br>
Ainda assim, podemos citar alguns bons momentos do disco. “Frantic” tem um ritmo veloz e intenso. A faixa-título, se não fosse tão repetitiva,
 poderia ser uma das melhores músicas da banda em muitos anos. E também as faixas, que já decaem um pouco, “Dirty Window” e a arrastada e esquisitona “The Unnamed Feeling”.<br><br>
