            Six years after the band’s last album of original songs, “St. Anger” was announced for release. Along with it came the promise that the band would return to the heavy and aggressive style of their early career.<br><br>
            During the composition and recording phase, the group experienced their second lineup change, once again with the bassist. This time, Jason Newsted left the band (or was kicked out) citing musical differences. The excellent Robert Trujillo (SUICIDAL TENDENCIES, OZZY OSBOURNE) was recruited to replace him. However, he did not participate in the recording of the new album. The bass was handled by producer Bob Rock.<br><br>
            As previously announced, the new album is heavy and aggressive. There are no ballads here, at most some light passages in a few songs. However, the biggest problem here is the production, which left everything sounding strange. The guitars are low, and the drums, besides being very loud, sound like a trash can. Another big mistake is the absence of guitar solos. It is very strange that the band decided to remove them from the songs, considering that Kirk Hammett has always been very good at it. As a result, many of the songs (all of which are between five and eight minutes long) become very repetitive. Without solos, they could at least be shorter.<br><br>
            However, “St. Anger” is far from matching the band’s classic albums. The compositions do not have the same refinement as before. Those songs were not just heavy. They were composed of inspired riffs and solos. Fast and technical drumming. Not to mention the bass. Where is the bass in “St. Anger”?<br><br>
            Still, we can mention some good moments of the album. “Frantic” has a fast and intense rhythm. The title track, if it weren’t so repetitive, could be one of the band’s best songs in many years. And also the tracks, which already decline a bit, “Dirty Window” and the dragging and weird “The Unnamed Feeling.”<br><br>
