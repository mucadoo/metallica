            One year after the release of their first album, “Ride the Lightning” was released, this time produced by the band themselves. Right away, we notice greater maturity in James Hetfield’s vocals, as he now has better control over his voice and no longer needs to scream as much as before.<br><br>
            This album has a more pronounced melodic vein compared to its predecessor, showing an evolution by the band, even though everything here remains quite heavy.<br><br>
            This is an album where it is difficult to make any criticisms, so choosing songs to highlight becomes a risky task, potentially committing injustices.<br><br>
            But I would dare to highlight the title track, “Fight Fire With Fire,” in addition to the classics “For Whom the Bell Tolls,” “Creeping Death,” and “Fade to Black.” The latter was the first time the band attempted something slower, close to a ballad. Even though it cannot be considered as such, as it has quite heavy passages, something similar to “Remember Tomorrow” from IRON MAIDEN's debut album. A band that is a declared influence on the American group, despite the eternal rivalry created between them by die-hard fans.<br><br>
            This album also features the instrumental “The Call of Ktulu,” which is nearly nine minutes long and shows a bit more of the band’s technical side, with beautiful guitar and bass solos, as well as good drum fills. Great music.<br><br>
            Overall, another one of the band’s best albums. And so as not to say that I didn’t mention all the songs, “Trapped Under Ice” and “Escape” are also excellent compositions.<br><br>
