Um ano após o lançamento do primeiro disco, é lançado “Ride the Lightning”, dessa vez produzido pela própria banda. Já de cara percebemos um maior 
amadurecimento do vocal de James Hetfield, que agora tem maior controle de sua voz e não precisa mais gritar tanto como antes.<br><br>
Este é um disco com uma veia melódica mais acentuada do que seu antecessor. Mostrando uma evolução por parte da banda, ainda que tudo aqui continue sendo bastante pesado.<br><br>
Este é um álbum onde é difícil fazer alguma ressalva, portanto escolher músicas a serem destacadas se torna uma tarefa arriscada, podendo fatalmente cometer injustiças. <br><br>
Mas ousaria destacar a faixa-título, “Fight Fire With Fire”, além das clássicas “For Whom the Bell Tolls”, “Creeping Death” e “Fade to Black”. Esta última foi a primeira 
vez que a banda tentou algo mais lento, próximo a uma balada. Ainda que não possa ser considerada dessa forma, pois têm passagens bastante pesadas, algo similar a “Remenber Tomorrow” 
do disco de estreia do IRON MAIDEN. Banda que é uma influencia declarada do grupo estadunidense, apesar da rivalidade eterna criada entre elas pelos fãs xiitas.<br><br>
Neste álbum também está presente a instrumental “The Call of Ktulu” que beira os nove minutos de duração e mostra um pouco mais do lado técnico da banda, com belos solos de 
guitarra e baixo, além de boas viradas na bateria. Ótima música.<br><br>
Enfim, outro dentre os melhores álbuns da banda. E pra não dizer que não falei de todas as músicas. “Trapped Under Ice” e “Escape” também são excelentes composições.<br><br>
