		<p class="paragrafo">
Depois dos fracos “Load” e “ReLoad”, o METALLICA volta a cena com “Garage Inc.”, um álbum duplo só com covers de 
grupos que serviram de influencia para a banda. Algumas gravações foram retiradas do EP de 1987 e novas versões 
foram gravadas especialmente para este lançamento. Entre as bandas homenageadas neste disco, estão DIAMON HEAD, 
BLACK SABBATH, MISFITS, MERCYFUL FATE, THIN LIZZY e MOTORHEAD.<br><br>
Com este disco, a banda deixa claro que ainda são bons no que fazem. Tanto que muitos dos covers aqui encontrados 
ficaram até melhores que suas versões originais e olha que elas foram gravadas por grandes bandas.<br><br>
Merece destaque as músicas “Die Die May Darling” e “Last Caress/Green Hell” do MISFITS, “Whiskey in the Jar” que se 
imortalizou na versão do THIN LIZZY, “Stone Cold Crazy” do QUEEN e a melhor de todas, “Am I Evil?” do DIAMOND HEAD.<br><br>
Um bom álbum que voltava a dar credibilidade à banda. Mesmo que os fãs continuassem com a pulga atrás da orelha, já que aqui
 só tem músicas de outras bandas.<br><br><br>
