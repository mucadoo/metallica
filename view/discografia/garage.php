        <p class="paragrafo">
            After the weak “Load” and “ReLoad” albums, METALLICA returned to the scene with “Garage Inc.,” a double album featuring only covers of groups that influenced the band. Some recordings were taken from the 1987 EP, and new versions were recorded especially for this release. Among the bands honored on this album are DIAMOND HEAD, BLACK SABBATH, MISFITS, MERCYFUL FATE, THIN LIZZY, and MOTORHEAD.<br><br>
            With this album, the band made it clear that they are still good at what they do. Many of the covers found here are even better than their original versions, and they were recorded by great bands.<br><br>
            Highlights include “Die, Die My Darling” and “Last Caress/Green Hell” by MISFITS, “Whiskey in the Jar” immortalized by THIN LIZZY, “Stone Cold Crazy” by QUEEN, and the best of all, “Am I Evil?” by DIAMOND HEAD.<br><br>
            A good album that restored the band’s credibility. Even though fans remained skeptical, as this album only features songs by other bands.<br><br><br>
