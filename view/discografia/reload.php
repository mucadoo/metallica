            After all the controversy surrounding “Load,” the band promised a return to their roots with a heavier album. Thus, “ReLoad” was released.<br><br>
            The new album was certainly heavier than its predecessor. However, it still didn’t compare to the first four albums. And even so, it was closer to “Load” than to anything else the band had released.<br><br>
            “ReLoad” starts off well with the first four tracks. “Fuel” has good riffs and a good chorus. “The Memory Remains” is also a good song and features the singer Marianne Faithfull, famous in the 60s. “Devil’s Dance” is quite nice and, despite being paced, is the heaviest track on the album. “The Unforgiven II” follows the same line as the first part, present in the “black album,” but it is much weaker.<br><br>
            From there, things go downhill, with songs that add nothing to the band’s career. Perhaps “Prince Charming” and “Low Man’s Lyric” are a bit better as they try to bring new elements to METALLICA's sound, but nothing else is worth saving. And they are probably not remembered by any fans at the band’s shows. If “Load” is a contender for the band’s worst album, “ReLoad” is its biggest competitor.<br><br>
