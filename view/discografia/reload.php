Depois de toda a polêmica criada em torno de “Load”, a banda promete voltar às origens, com um álbum mais pesado. É lançado então “ReLoad”.<br><br>
O novo disco era com certeza mais pesado que seu antecessor. Porém nem chegava aos pés dos quatro primeiros. E mesmo assim estava mais próximo de “Load”
 do que de qualquer outra coisa lançada pela banda.<br><br>
“ReLoad” até começa bem nas quatro primeiras faixas. “Fuel” tem bons riffs e um bom refrão. “The Memory Remains” também é uma boa música e conta com
 a participação da cantora Marianne Faithfull, famosa nos anos 60. “Devil’s Dance” é bem legal e apesar de cadenciada é a faixa mais pesada do disco.
 E “The Unforgiven II” vai na mesma linha da primeira parte, presente no “álbum preto”, porém é bem mais fraca.<br><br>
Daí pra frente à coisa descamba de vez, músicas que não acrescentam em nada a carreira da banda. Talvez “Prince Charming” e “Low Man’s Lyric” sejam um pouco
 melhores, pois tentam trazer novos elementos ao som do METALLICA, de resto nada mais se salva. E provavelmente não são lembradas por nenhum fã nos shows do 
 grupo. Se “Load” é candidato à pior disco da banda, “ReLoad” é seu maior concorrente.<br><br>
